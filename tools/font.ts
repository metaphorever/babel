/** Width in pixels of text at a scale (3 px per letter plus 1 px spacing). */
export function textWidth(text: string, scale = 1): number {
  return text.length * 4 * scale - scale;
}

/** Draw text with its top-left at (x, y) by calling plot for every ink pixel. */
export function drawText(text: string, x: number, y: number, plot: (x: number, y: number) => void, scale = 1): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch] ?? GLYPHS['?'];
    g.forEach((row, gy) => {
      for (let gx = 0; gx < 3; gx++) {
        if (row[gx] !== '1') continue;
        for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) plot(cx + gx * scale + sx, y + gy * scale + sy);
      }
    });
    cx += 4 * scale;
  }
}
